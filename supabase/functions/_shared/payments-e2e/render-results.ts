// Renders docs/test-plans/payments-e2e.results.md from the recorded
// evidence file plus the cell manifest (design AD-7). The results document
// is never hand-written — every row here is traced back to an evidence
// record, or is explicitly listed as not-run.
//
//   deno run -A supabase/functions/_shared/payments-e2e/render-results.ts

import { readEvidence, type EvidenceRecord } from "./evidence.ts";

interface ManifestCell {
  cell_id: string;
  requirement_ids: string[];
  currency: string;
  intent: string;
  scenario: string;
  applicable: boolean;
  reason_if_not_applicable?: string;
}

interface Manifest {
  cells: ManifestCell[];
}

async function loadManifest(): Promise<Manifest> {
  const raw = await Deno.readTextFile("docs/test-plans/payments-e2e.cells.json");
  return JSON.parse(raw);
}

function resultBadge(result: EvidenceRecord["result"] | "not-run"): string {
  switch (result) {
    case "pass":
      return "PASS";
    case "fail":
      return "FAIL";
    case "n/a":
      return "N/A";
    default:
      return "NOT RUN";
  }
}

async function main() {
  const manifest = await loadManifest();
  const evidence = await readEvidence();
  const byCellId = new Map(evidence.map((e) => [e.cell_id, e]));

  const lines: string[] = [];
  lines.push("# Payments E2E — Results");
  lines.push("");
  lines.push(`Rendered ${new Date().toISOString()} from ${evidence.length} evidence record(s) against ${manifest.cells.length} manifest cell(s).`);
  lines.push("");
  lines.push("_Generated by render-results.ts — do not hand-edit. Re-run the harness and this script to update._");
  lines.push("");
  lines.push("## Cell results");
  lines.push("");
  lines.push("| Cell | Currency | Intent | Scenario | Tier | Result | Note |");
  lines.push("|---|---|---|---|---|---|---|");

  let passCount = 0, failCount = 0, naCount = 0, notRunCount = 0;

  for (const cell of manifest.cells) {
    if (!cell.applicable) {
      lines.push(`| ${cell.cell_id} | ${cell.currency} | ${cell.intent} | ${cell.scenario} | n/a | N/A | ${cell.reason_if_not_applicable ?? ""} |`);
      naCount++;
      continue;
    }
    const record = byCellId.get(cell.cell_id);
    if (!record) {
      lines.push(`| ${cell.cell_id} | ${cell.currency} | ${cell.intent} | ${cell.scenario} | — | NOT RUN | no evidence recorded |`);
      notRunCount++;
      continue;
    }
    const badge = resultBadge(record.result);
    if (record.result === "pass") passCount++;
    else if (record.result === "fail") failCount++;
    else if (record.result === "n/a") naCount++;
    else notRunCount++;
    lines.push(`| ${cell.cell_id} | ${record.currency} | ${record.intent} | ${record.scenario} | ${record.tier} | ${badge} | ${record.note.replace(/\|/g, "\\|")} |`);
  }

  lines.push("");
  lines.push(`**Totals:** ${passCount} pass, ${failCount} fail, ${naCount} n/a, ${notRunCount} not-run.`);
  lines.push("");

  lines.push("## Requirement coverage");
  lines.push("");
  const requirementIds = Array.from(new Set(manifest.cells.flatMap((c) => c.requirement_ids))).sort();
  lines.push("| Requirement | Cells with a passing record | Unevidenced |");
  lines.push("|---|---|---|");
  for (const req of requirementIds) {
    const cellsForReq = manifest.cells.filter((c) => c.requirement_ids.includes(req));
    const passing = cellsForReq.filter((c) => byCellId.get(c.cell_id)?.result === "pass");
    const unevidenced = cellsForReq.length > 0 && passing.length === 0;
    lines.push(`| ${req} | ${passing.map((c) => c.cell_id).join(", ") || "—"} | ${unevidenced ? "**YES**" : ""} |`);
  }
  lines.push("");

  lines.push("## Verdict");
  lines.push("");
  lines.push("_This section is written by the run's verdict author against the evidence above (design AD-10) — it is not auto-derived, and render-results.ts never fills it in._");
  lines.push("");
  lines.push("- **(a) Payout path — go/no-go:** _TODO, resting on cells: ..._");
  lines.push("- **(b) subaccount-split-cleanup unblocked:** _TODO_");
  lines.push("- **(c) beta launch unblocked:** _TODO_");
  lines.push("");

  await Deno.writeTextFile("docs/test-plans/payments-e2e.results.md", lines.join("\n") + "\n");
  console.log(`Wrote docs/test-plans/payments-e2e.results.md (${passCount} pass, ${failCount} fail, ${naCount} n/a, ${notRunCount} not-run)`);
}

if (import.meta.main) {
  await main();
}
